// NOTICE и THIRD_PARTY консоли из сборки: vite (build.license) кладёт в
// dist/third-party-licenses.md имена, версии, лицензии и их тексты для
// всех пакетов, попавших в бандл. Скрипт проверяет, что лицензии
// совместимы с распространением консоли под AGPL-3.0 и двойным
// лицензированием, и собирает из файла THIRD_PARTY и NOTICE (NOTICE-файлы
// пакетов из node_modules).
//
//   npm run build && npm run third-party           # обновить файлы
//   npm run build && npm run third-party -- --check  # сверить (CI)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = path.join(ROOT, 'dist', 'third-party-licenses.md')

// Разрешённые лицензии: пермиссивные, без копилефта.
const ALLOWED = new Set(['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'CC0-1.0', 'Unlicense', 'BlueOak-1.0.0'])
// Пакеты без поля license в package.json: лицензия проверена по файлу
// лицензии пакета руками. Новая версия такого пакета проверяется заново.
const REVIEWED = { 'khroma@2.1.0': 'MIT' }

// Выражение SPDX разрешено, если хотя бы одна альтернатива OR целиком
// (все части AND) из разрешённых: (MPL-2.0 OR Apache-2.0) берётся под
// Apache-2.0.
function allowed(expr) {
  return expr.replace(/[()]/g, '').split(/\s+OR\s+/).some(alt => alt.split(/\s+AND\s+/).every(id => ALLOWED.has(id.trim())))
}

function read(p) {
  return readFileSync(p, 'utf8').replace(/\r\n/g, '\n').replace(/^\n+|\n+$/g, '')
}

if (!existsSync(SOURCE)) {
  console.error(`third-party: нет ${path.relative(ROOT, SOURCE)}: сначала npm run build`)
  process.exit(1)
}
const md = read(SOURCE)
const heading = /^## (\S+) - (\S+)(?: \((.+)\))?$/gm
const pkgs = [...md.matchAll(heading)].map(m => ({ name: m[1], version: m[2], license: m[3] }))
if (pkgs.length === 0) {
  console.error('third-party: в файле лицензий vite нет пакетов: формат файла изменился?')
  process.exit(1)
}
const bad = []
for (const p of pkgs) {
  const lic = p.license ?? REVIEWED[`${p.name}@${p.version}`]
  if (!lic) bad.push(`${p.name}@${p.version}: лицензия не указана, проверьте файл лицензии пакета и внесите в REVIEWED`)
  else if (!allowed(lic)) bad.push(`${p.name}@${p.version}: ${lic} не из разрешённых (${[...ALLOWED].join(', ')})`)
}
if (bad.length) {
  console.error('third-party: лицензии зависимостей консоли:\n  ' + bad.join('\n  '))
  process.exit(1)
}

const body = md.replace(/^# Licenses\s*\n+The app bundles[^\n]*\n+/, '')
const third = [
  'THIRD-PARTY SOFTWARE NOTICES AND LICENSES',
  '=========================================',
  '',
  'Third-party packages bundled into the Rivet web console (and into rivetd,',
  'which embeds the console) and their licenses. Generated by',
  '`npm run third-party` from the vite build; do not edit by hand.',
  '',
  'Сторонние пакеты, которые входят в сборку веб-консоли Rivet (и в rivetd,',
  'куда консоль встраивается), и тексты их лицензий. Файл собирает',
  '`npm run third-party` из сборки vite, руками не правится.',
  '',
  body,
  '',
].join('\n')

const RULE = '-'.repeat(78)
const notices = []
for (const p of pkgs) {
  const dir = path.join(ROOT, 'node_modules', p.name)
  if (!existsSync(dir)) continue
  for (const f of readdirSync(dir).filter(f => /^NOTICE(\.(md|txt))?$/i.test(f)).sort()) {
    notices.push(`${RULE}\n${p.name} ${p.version}: ${f}\n${RULE}\n${read(path.join(dir, f))}\n`)
  }
}
const notice = [
  'Rivet web console',
  'Copyright (C) 2026 Vladimir Pavlunin',
  '',
  'This product bundles third-party packages whose NOTICE files must be',
  'reproduced. Their notices follow; full license texts are in THIRD_PARTY.',
  'Generated by `npm run third-party`; do not edit by hand.',
  '',
  notices.join('\n'),
].join('\n')

const check = process.argv.includes('--check')
const stale = []
for (const [file, text] of [['THIRD_PARTY', third], ['NOTICE', notice]]) {
  const p = path.join(ROOT, file)
  const old = existsSync(p) ? readFileSync(p, 'utf8') : ''
  if (old === text) continue
  stale.push(file)
  if (!check) writeFileSync(p, text)
}
if (check && stale.length) {
  console.error(`third-party: устарели ${stale.join(', ')}: выполните npm run build && npm run third-party`)
  process.exit(1)
}
